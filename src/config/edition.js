// Festival edition — the ONLY value to change for the next year's festival (2027, 2028 …).
// Every "Durgotsav 2026" / "Amrut Durgotsav 2026" on the website is built from it: index.html (%EDITION_YEAR%),
// page titles, header, footer, hero, award page URL, fallback dates and certificate file names.
// Past events (UNESCO listing 2025, 2025 world record, 2025 gallery/podcasts) are history and stay as written.
// Keep it equal to EDITION_YEAR in backend/ and admin/ src/config/edition.js: the browser console warns when
// the API reports a different edition_year.
// Kept free of imports: vite.config.js reads this file too.
export const EDITION_YEAR = 2026;

const DEVANAGARI = "०१२३४५६७८९";

// "२०२६" — the same year in Marathi digits
export const EDITION_YEAR_MR = String(EDITION_YEAR).replace(/\d/g, (d) => DEVANAGARI[d]);

// "DGT26" — prefix of registration numbers (DGT26-000123) and certificate numbers (AMRUT-DGT26-000123),
// generated by the API from its own EDITION_YEAR
export const NUMBER_PREFIX = `DGT${String(EDITION_YEAR).slice(-2)}`;

// editionDate("11-05") → "2026-11-05": a calendar date of the current edition, for fallbacks until settings load
export const editionDate = (monthDay) => `${EDITION_YEAR}-${monthDay}`;
